// Renders benchmark results (JSON) as Markdown. Pure formatting: every number comes from `out`.
const fmt = (n, d = 3) => (n == null ? '—' : Number(n).toFixed(d));
const int = (n) => (n == null ? '—' : Number(n).toLocaleString('en-US'));
const mib = (b) => (b == null ? 'n/a' : `${(Number(b) / 1024 / 1024).toFixed(1)} MiB`);
const ratio = (a, b) => (a && b ? `${(Number(a) / Number(b)).toFixed(1)}×` : '—');

function planCell(p) {
  const t = p.plan?.analyze?.tables?.[0];
  const e = p.plan?.explain?.[0];
  if (!e) return '—';
  return `${e.type}${e.key ? ` / ${e.key}` : ''}${e.partitions ? ` / parts: ${e.partitions.split(',').length}` : ''}${t?.r_rows != null ? ` / r_rows ${fmt(t.r_rows, 1)}` : ''}`;
}

export function renderReport(out, jsonRel) {
  const e = out.environment;
  const L = [];
  L.push('# Benchmark report', '');
  L.push(`Generated by \`npm run benchmark\` on ${e.timestamp}. Raw results: [\`${jsonRel}\`](${jsonRel}).`, '');
  L.push('> All values below were produced by executing the queries shown. Latencies are client-side wall-clock times of',
    '> server-side prepared statements over a local TCP connection (Node.js → Docker Desktop VM), so they include protocol overhead.',
    `> ${e.cache}`, '');
  L.push('## Environment', '');
  L.push('| Item | Value |', '|---|---|');
  L.push(`| MariaDB | ${e.mariadb.version} (${e.mariadb.machine}), buffer pool ${mib(e.mariadb.innodb_buffer_pool_size)}, page ${e.mariadb.innodb_page_size} B |`);
  L.push(`| Client | Node.js ${e.client.node}, ${e.client.platform} ${e.client.arch}, ${e.client.cpus} × ${e.client.cpu_model}, ${mib(e.client.total_mem_bytes)} RAM |`);
  L.push(`| Dataset | ${int(e.dataset.ingested_articles)} articles, ${int(e.dataset.revisions)} revisions, ${int(e.dataset.timeline_rows)} timeline rows (${int(e.dataset.timeline_row_versions)} row versions incl. system history), page_mirror ${int(e.dataset.mirror_row_versions)} row versions |`);
  L.push(`| Window | ${e.dataset.window[0]} → ${e.dataset.window[1]} |`, '');

  const lk = out.suites.lookup;
  if (lk) {
    L.push('## 1. "Which revision was live at T?" — strategies on the real dataset', '');
    L.push(`Workload: ${int(lk.queries)} (article, instant) pairs drawn uniformly (seed ${lk.seed}) over ${lk.articles} articles and the whole window; each strategy runs the same workload ${lk.reps}× after a warm-up pass.`,
      '“Handler reads/query” is the per-execution delta of the session `Handler_read_*` counters — the number of index/row reads the storage engine performed (a rows-examined proxy). “Disagreements” counts answers that differ from the production query (must be 0).', '');
    L.push('| Strategy | median ms | p95 ms | p99 ms | mean ms | handler reads/query | plan (sample) | disagreements |', '|---|---:|---:|---:|---:|---:|---|---:|');
    for (const r of lk.results) {
      const dis = r.disagreementsWithProduction ?? (r.differsFromToday != null ? `n/a (${r.differsFromToday} differ from today — expected)` : '—');
      L.push(`| ${r.label} | ${fmt(r.latency.median)} | ${fmt(r.latency.p95)} | ${fmt(r.latency.p99)} | ${fmt(r.latency.mean)} | ${fmt(r.handlerReadsPerQuery, 1)} | ${planCell(r)} | ${dis} |`);
    }
    L.push('', '<details><summary>SQL and ANALYZE FORMAT=JSON summaries</summary>', '');
    for (const r of lk.results) {
      L.push(`**${r.key}**`, '', '```sql', r.sql, '```', '');
      L.push('```json', JSON.stringify({ explain: r.plan.explain, analyze: r.plan.analyze, handlerBreakdownPerQuery: r.handlerBreakdownPerQuery }, null, 2), '```', '');
    }
    L.push('</details>', '');
  }

  const pt = out.suites.partition;
  if (pt) {
    L.push('## 2. Partitioning by SYSTEM_TIME — derived stress dataset', '');
    L.push(`**Synthetic / derived data.** ${pt.scale} copies of the real \`page_mirror\` history (all row versions), article ids shifted by k × 1,000,000, `
      + 'timestamps (row_start/row_end) copied unchanged via `system_versioning_insert_history`. The temporal distribution is that of the real Wikipedia data; '
      + 'the articles are not real. All three tables contain identical rows; only the physical layout differs.', '');
    L.push('| Table | layout | row versions | current | history | data+index | allocated file size | build s |', '|---|---|---:|---:|---:|---:|---:|---:|');
    for (const t of pt.tables) {
      L.push(`| \`${t.table}\` | ${t.label} | ${int(t.info.rows_total)} | ${int(t.info.rows_current)} | ${int(t.info.rows_history)} | ${mib(Number(t.info.data_length) + Number(t.info.index_length))} | ${mib(t.info.allocated_size)} | ${fmt(t.buildSeconds, 1)} |`);
    }
    L.push('');
    L.push(`Point workloads: ${int(pt.pointQueries)} queries × ${pt.reps}; scan workloads: ${pt.scanQueries} queries × ${pt.reps} (5 for ALL).`, '');
    L.push('| Query | table | median ms | p95 ms | handler reads/query | partitions scanned (EXPLAIN) | same answers |', '|---|---|---:|---:|---:|---|:---:|');
    for (const q of pt.results) {
      for (const r of q.perTable) {
        const parts = r.plan.explain[0]?.partitions;
        L.push(`| ${q.label} | \`${r.table}\` | ${fmt(r.latency.median)} | ${fmt(r.latency.p95)} | ${int(Math.round(r.handlerReadsPerQuery))} | ${parts ? `${parts.split(',').length}: ${parts.length > 40 ? parts.slice(0, 37) + '…' : parts}` : '(not partitioned)'} | ${r.sameAnswersAsUnpartitioned ? '✓' : '✗'} |`);
      }
    }
    if (pt.maintenance?.length) {
      L.push('', '### Retention: removing history older than 2023-01-01', '');
      L.push('| Table | method | statement | rows removed | ms |', '|---|---|---|---:|---:|');
      for (const m of pt.maintenance) L.push(`| \`${m.table}\` | ${m.label} | \`${m.sql}\` | ${int(m.rows_removed)} | ${fmt(m.ms, 1)} |`);
    }
    L.push('');
  }

  const st = out.suites.storage;
  if (st) {
    L.push('## 3. Storage and growth — real dataset', '');
    L.push('| Table | system-versioned | rows (all versions) | current | history | data+index (estimate) | allocated file size |', '|---|:---:|---:|---:|---:|---:|---:|');
    for (const t of st.tables) L.push(`| \`${t.table}\` | ${t.versioned ? 'yes' : 'no'} | ${int(t.rows_total)} | ${int(t.rows_current)} | ${t.versioned ? int(t.rows_history) : '—'} | ${mib(Number(t.data_length ?? 0) + Number(t.index_length ?? 0))} | ${mib(t.allocated_size)} |`);
    L.push('');
    L.push(`Revision texts: ${int(st.revisions.revisions)} revisions whose sizes add up to ${mib(st.revisions.sum_revision_sizes)}; `
      + `${int(st.content.texts)} distinct texts (${mib(st.content.raw_bytes)}) stored in ${int(st.content.chunks)} Brotli chunks totalling ${mib(st.content.stored_bytes)} `
      + `(${ratio(st.content.raw_bytes, st.content.stored_bytes)} smaller than the distinct texts, ${ratio(st.revisions.sum_revision_sizes, st.content.stored_bytes)} smaller than one full copy per revision).`, '');
    L.push('`page_mirror` row versions per partition (history rows are routed by `row_end`); “inline text” = what these row versions would weigh if each carried the full article text:', '');
    L.push('| Partition | upper bound | row versions | inline text |', '|---|---|---:|---:|');
    for (const p of st.mirrorPartitions) L.push(`| ${p.name} | ${p.upper_bound} | ${int(p.rows)} | ${mib(p.inline_text_bytes_if_stored)} |`);
    const x = st.inlineExperiment;
    L.push('', '### Measured: full text inside the system-versioned row', '');
    L.push(`${int(x.revisionsReplayed)} real revisions of ${x.articles.length} articles (chosen at size quantiles: ${x.articles.map((a) => a.canonical_title).join(', ')}) `
      + `were replayed into two system-versioned tables holding the text in the row. Raw text replayed: ${mib(x.rawTextBytes)}.`, '');
    L.push('| Storage | allocated file size (data+index estimate) | compression (raw text ÷ size) |', '|---|---:|---:|');
    for (const t of x.tables) {
      const size = t.allocated_size ?? (Number(t.data_length) + Number(t.index_length));
      L.push(`| \`${t.table}\` (${int(t.rows_total)} row versions) | ${mib(t.allocated_size)} (${mib(Number(t.data_length) + Number(t.index_length))}) | ${ratio(x.rawTextBytes, size)} |`);
    }
    L.push(`| this project's chunk store for the same articles (\`content_chunks\`, distinct texts only) | ${mib(x.chunkStore.stored_bytes)} | ${ratio(x.rawTextBytes, x.chunkStore.stored_bytes)} |`, '');
  }
  L.push(`_Total benchmark duration: ${fmt(out.durationSeconds, 1)} s._`, '');
  return L.join('\n');
}

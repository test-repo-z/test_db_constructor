#!/usr/bin/env node
// npm run resolve-articles
// Reads data/articles.json (curated, authoritative, never modified) and writes the GENERATED manifest
// data/articles.resolved.json plus a human-readable summary.
import fs from 'node:fs';
import { config, resolvePath } from '../src/config/index.js';
import { createLogger } from '../src/lib/logger.js';
import { isMain } from '../src/lib/cli.js';
import { WikipediaClient } from '../src/wikipedia/client.js';
import { resolveArticles } from '../src/wikipedia/resolver.js';
import { summarize, validateCuratedList } from '../src/wikipedia/resolution.js';

const log = createLogger('resolve');

export function readCuratedList() {
  const list = JSON.parse(fs.readFileSync(resolvePath(config.sources.articles), 'utf8'));
  const problems = validateCuratedList(list, config.sources.expectedArticleCount);
  if (problems.length) {
    for (const p of problems) log.error(p);
    throw new Error(`curated list ${config.sources.articles} failed validation (${problems.length} problems)`);
  }
  return list;
}

export function makeClient() {
  return new WikipediaClient({ ...config.wikipedia, userAgent: config.userAgent });
}

export async function runResolution() {
  const curated = readCuratedList();
  const client = makeClient();
  const started = Date.now();
  const records = await resolveArticles(client, curated, { titlesPerQuery: config.wikipedia.titlesPerQuery, log });
  const summary = summarize(records);
  const manifest = {
    $comment: 'GENERATED by `npm run resolve-articles` from data/articles.json. Do not edit by hand; the curated list is the source of truth.',
    generated_at: new Date().toISOString(),
    source: config.sources.articles,
    api: config.wikipedia.apiUrl,
    summary,
    articles: records,
  };
  fs.writeFileSync(resolvePath(config.sources.resolved), JSON.stringify(manifest, null, 2) + '\n');
  log.info('resolution finished', { elapsedMs: Date.now() - started, apiRequests: client.stats.requests });
  return { manifest, summary };
}

export function printSummary(summary, records) {
  const lines = [
    `Requested:      ${summary.requested}`,
    `Resolved:       ${summary.resolved}`,
    `Redirects:      ${summary.redirect}`,
    `Missing:        ${summary.missing}`,
    `Disambiguation: ${summary.disambiguation}`,
    `Duplicates:     ${summary.duplicate}`,
    `Errors:         ${summary.error}`,
    `Usable (resolved + redirect): ${summary.usable}`,
  ];
  console.log(lines.join('\n'));
  const notable = records.filter((r) => r.status !== 'resolved');
  if (notable.length) {
    console.log('\nNon-trivial resolutions:');
    for (const r of notable) {
      console.log(`  [${r.status}] "${r.requested_title}" -> ${r.canonical_title ?? '(none)'}` +
        `${r.redirect_fragment ? ` #${r.redirect_fragment}` : ''}${r.reason ? `  (${r.reason})` : ''}`);
    }
  }
}

if (isMain(import.meta.url)) {
  runResolution()
    .then(({ manifest, summary }) => printSummary(summary, manifest.articles))
    .catch((err) => {
      log.error(err.message);
      process.exit(1);
    });
}
